import assert from 'node:assert/strict';
import { once } from 'node:events';
import { mkdir, readFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { chromium } from 'playwright';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { demoServer } from '../examples/site.js';
const run = promisify(execFile);
const root = resolve('artifacts', 'studio-test-' + Date.now());
await mkdir(root, { recursive: true });
const fixture = demoServer().listen(0, '127.0.0.1');
await once(fixture, 'listening');
const address = fixture.address(); assert.ok(address && typeof address !== 'string');
const url = `http://127.0.0.1:${address.port}/`;
const extension = resolve('extension');
const profile = join(root, 'profile');
const context = await chromium.launchPersistentContext(profile, { executablePath: chromium.executablePath(), headless: true, args: ['--remote-debugging-port=0', '--disable-extensions-except=' + extension, '--load-extension=' + extension] });
const client = new Client({ name: 'studio-test', version: '1' });
let generated: Client | undefined;
try {
  const page = await context.newPage(); await page.goto(url);
  await page.evaluate(() => localStorage.setItem('auth-proof', 'existing-session'));
  const worker = context.serviceWorkers()[0] ?? await context.waitForEvent('serviceworker');
  const popup = await context.newPage(); await popup.goto(`chrome-extension://${new URL(worker.url()).host}/popup.html`);
  await page.bringToFront();
  await client.connect(new StdioClientTransport({ command: process.execPath, args: ['--import', 'tsx', resolve('src/studio/index.ts')], env: { ...Object.fromEntries(Object.entries(process.env).filter((e): e is [string, string] => e[1] !== undefined)), STUDIO_ROOT: root } }));
  const call = async (c: Client, name: string, args = {}) => {
    const result = await c.callTool({ name, arguments: args });
    assert.ok(!result.isError, JSON.stringify(result));
    return JSON.parse((result.content as { text: string }[])[0].text);
  };
  const pairExtension = async (pairingUrl: string) => {
    await page.bringToFront();
    const reply = await popup.evaluate(async pairingUrl => (globalThis as any).chrome.runtime.sendMessage({ type: 'pair', pairingUrl }), pairingUrl);
    assert.equal(reply.ok, true, JSON.stringify(reply));
  };
  const discovery = 'http://127.0.0.1:43119/pairing';
  assert.equal((await fetch(discovery)).status, 403);
  assert.equal((await fetch(discovery, { headers: { 'X-Studio-Extension': 'a'.repeat(32), Origin: 'https://evil.example' } })).status, 403);
  assert.equal((await fetch(discovery, { method: 'OPTIONS', headers: { Origin: 'https://evil.example' } })).status, 403);
  const pairing = await (await fetch(discovery, { headers: { 'X-Studio-Extension': 'a'.repeat(32) } })).json() as { pairingUrl: string };
  assert.equal((await fetch(new URL(pairing.pairingUrl).origin + '/next')).status, 403);
  assert.equal((await fetch(new URL(pairing.pairingUrl).origin + '/next', { headers: { Authorization: 'Bearer ' + new URL(pairing.pairingUrl).hash.slice(1), Origin: 'https://evil.example' } })).status, 403);
  const armed = await popup.evaluate(async () => (globalThis as any).chrome.runtime.sendMessage({ type: 'auto', enabled: true }));
  assert.equal(armed.ok, true);
  await popup.waitForFunction(async () => (await (globalThis as any).chrome.runtime.sendMessage({ type: 'status' })).bridgeConnected);
  const autoState = await popup.evaluate(async () => (globalThis as any).chrome.runtime.sendMessage({ type: 'status' }));
  assert.equal(autoState.autoTarget.origin, new URL(url).origin);
  const disarmed = await popup.evaluate(async () => (globalThis as any).chrome.runtime.sendMessage({ type: 'auto', enabled: false }));
  assert.equal(disarmed.ok, true, JSON.stringify(disarmed));
  assert.equal((await popup.evaluate(async () => (globalThis as any).chrome.runtime.sendMessage({ type: 'status' }))).autoTarget, null);
  await pairExtension(''); // Discovery also works with the one-shot Connect button.
  await call(client, 'studio_start', { name: 'site', url, endpoint: 'extension' });
  const snapshot = await call(client, 'studio_inspect');
  assert.ok(snapshot.controls.some((c: any) => c.selector === '#search'));
  await call(client, 'studio_workflow_begin');
  await call(client, 'studio_fill', { selector: '#search', value: 'first-agent-query', parameter: 'query' });
  await call(client, 'studio_click', { selector: '#go' });
  await call(client, 'studio_scroll', { pixels: 700 });
  await call(client, 'studio_wait', { selector: '#result' });
  assert.match(JSON.stringify(await call(client, 'studio_extract', { selector: '#result' })), /first-agent-query/);
  assert.ok((await call(client, 'studio_network')).some((e: any) => e.path === '/api/search'));
  assert.ok((await call(client, 'studio_api_preview')).paths['/api/search']);
  assert.ok((await call(client, 'studio_runtime')).scripts.length > 0);
  await call(client, 'studio_workflow_save', { name: 'search', description: 'Search the fixture and return matching items.', resultSelector: '#result' });
  const result = await call(client, 'studio_finish');
  assert.ok(!page.isClosed());
  assert.equal(await page.evaluate(() => localStorage.getItem('auth-proof')), 'existing-session');
  assert.ok(!(await readFile(join(result.output, 'workflows.json'), 'utf8')).includes('first-agent-query'), 'Recorded input values must not enter generated workflows');
  const [port] = (await readFile(join(profile, 'DevToolsActivePort'), 'utf8')).split('\n');
  await call(client, 'studio_start', { name: 'cdp_site', url, endpoint: 'http://127.0.0.1:' + port });
  await call(client, 'studio_fill', { selector: '#search', value: 'direct-studio', parameter: 'query' });
  await call(client, 'studio_click', { selector: '#go' });
  assert.match(JSON.stringify(await call(client, 'studio_extract', { selector: '#result' })), /direct-studio/);
  assert.ok((await call(client, 'studio_api_preview')).paths['/api/search']);
  await call(client, 'studio_close');
  assert.ok(!page.isClosed());
  await run(process.execPath, [resolve('node_modules/typescript/bin/tsc'), '-p', join(result.output, 'tsconfig.json')]);
  generated = new Client({ name: 'generated-workflow-test', version: '1' });
  await generated.connect(new StdioClientTransport({ command: process.execPath, args: [join(result.output, 'dist/index.js')], env: { MCP_BROWSER_CDP: 'http://127.0.0.1:' + port } }));
  assert.match(JSON.stringify(await call(generated, 'browser_search', { query: 'replayed-over-cdp' })), /replayed-over-cdp/);
  // Wait for the previous extension connection to observe Studio shutdown.
  await popup.waitForFunction(async () => !(await (globalThis as any).chrome.runtime.sendMessage({ type: 'status' })).bridgeConnected);
  const nextPair = await call(generated, 'browser_connect_extension');
  await pairExtension(nextPair.pairingUrl);
  assert.match(JSON.stringify(await call(generated, 'browser_search', { query: 'replayed-over-extension' })), /replayed-over-extension/);
  assert.ok(!page.isClosed());
  await popup.reload(); await popup.setViewportSize({ width: 400, height: 850 });
  await popup.screenshot({ path: join(root, 'connected-extension.png') });
  console.log('PASS: real MCP tools over extension and CDP → inspect/fill/click/scroll/extract/network/API preview/runtime → generated MCP → parameterized replay over CDP and extension. Browser session preserved; unauthorized bridge requests rejected.');
  console.log('Artifacts: ' + root);
} finally {
  await generated?.close(); await client.close(); await context.close();
  fixture.closeAllConnections(); await new Promise<void>(done => fixture.close(() => done()));
}
